# ------------------------------------------------------------------ زمان
_HMS = re.compile(r"(\d+):(\d{1,2})(?::(\d{1,2}(?:[.,]\d+)?))?")


def sec_to_hms(seconds: float) -> str:
    """ثانیه را به h:mm:ss تبدیل می‌کند (برای نمایش در خروجی)."""
    seconds = max(0, int(seconds))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    if h:
        return f"{h}:{m:02d}:{s:02d}"
    return f"{m:02d}:{s:02d}"


def hms_to_sec(text: str) -> float:
    """سازگار با ورودی‌های کاربری: تبدیل 'h:mm:ss[.ms]' یا ثانیهٔ عددی به float."""
    text = str(text).strip()
    if not text:
        return 0.0
    if text.replace(".", "", 1).replace(",", "", 1).isdigit():
        return float(text.replace(",", "."))
    m = _HMS.match(text)
    if not m:
        raise ValueError(f"فرمت زمان نامعتبر: {text!r}")
    g = m.groups()
    parts = text.count(":")
    if parts == 1:
        mi = int(g[0])
        s = float(g[1].replace(",", ".")) if g[1] else 0.0
        h = 0
    else:
        h = int(g[0])
        mi = int(g[1])
        s = float(g[2].replace(",", ".")) if g[2] else 0.0
    return h * 3600 + mi * 60 + s


